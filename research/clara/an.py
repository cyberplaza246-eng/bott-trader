import pandas as pd,numpy as np
t=pd.read_csv('nt300.csv')
m=lambda s:s.astype(str).str.replace(r'[\$,]','',regex=True).str.replace(r'^\((.*)\)$',r'-\1',regex=True).astype(float)
for c in ['Profit','MAE','MFE']: t[c]=m(t[c])
t['et']=pd.to_datetime(t['Entry time']);t['xt']=pd.to_datetime(t['Exit time'])
t['pts']=np.where(t['Market pos.']=='Long',1,-1)*(t['Exit price']-t['Entry price'])
print(len(t),t.Profit.sum(),(t.Profit>0).mean())
print(t['Market pos.'].value_counts());print(t['Exit name'].value_counts())
print(t.groupby('Exit name').pts.describe())
print(t.et.dt.strftime('%H:%M').str[:4].value_counts().sort_index())
print(t.xt.dt.strftime('%H').value_counts().sort_index())
print('dur min',((t.xt-t.et).dt.total_seconds()/60).describe())
print(t.Qty.value_counts().head())
# implied stop distance: risk 300/qty -> pts
t['d']=t.et.dt.date;print('trades/day',t.groupby('d').size().value_counts())
print('2nd trade win',t[t.groupby('d').cumcount()==1].Profit.gt(0).mean())
print(t.groupby(t.et.dt.year).agg(n=('Profit','size'),net=('Profit','sum'),wr=('Profit',lambda x:(x>0).mean())))
print(t[['et','Market pos.','Qty','Entry price','Exit price','Exit name','pts','MAE','MFE']].tail(15).to_string())
t.to_pickle('t.pkl')
