import json
S={}
S['og_sweeps_only']=dict(fb_mode='off',_save=1)
S['og_fb_on']=dict(fb_mode='on',_save=1)
S['fb_only']=dict(fb_mode='only',_save=1)
for nm,b in (('sw',dict(fb_mode='off')),('fb',dict(fb_mode='on'))):
    S[nm+'_day']=dict(b,only_session='day')
    S[nm+'_ovn']=dict(b,only_session='overnight')
    S[nm+'_lock_off']=dict(b,lock=False)
    S[nm+'_lock_tight']=dict(b,lock_act=60.,lock_keep=20.,lock_trail_start=100.)
    S[nm+'_lock_wide']=dict(b,lock_act=200.,lock_keep=60.,lock_trail_start=300.)
    S[nm+'_pos1']=dict(b,max_pos=1)
    S[nm+'_pos2']=dict(b,max_pos=2)
    S[nm+'_size1']=dict(b,size_mode='fixed1',max_contracts=1)
    S[nm+'_tp_r1']=dict(b,tp_mode='r',tp_r=1.0)
    S[nm+'_tp_r15']=dict(b,tp_mode='r',tp_r=1.5)
    S[nm+'_tp_r2']=dict(b,tp_mode='r',tp_r=2.0)
    S[nm+'_long_only']=dict(b,long_only=True)
    S[nm+'_short_only']=dict(b,short_only=True)
    S[nm+'_no_sun']=dict(b,skip_sunday=True)
    S[nm+'_sl08']=dict(b,sl_scale=0.8)
    S[nm+'_sl12']=dict(b,sl_scale=1.25)
    S[nm+'_nolimits']=dict(b,session_limits=False)
for r in (['trending'],['ranging'],['trending','ranging']):
    S['fb_reg_'+'_'.join(r)]=dict(fb_mode='on',fb_regimes=r)
S['fb_conf_hi']=dict(fb_mode='on',fb_conf=0.66)
S['fb_stress_slip2']=dict(fb_mode='on',slip_ticks=2)
S['sw_stress_slip2']=dict(fb_mode='off',slip_ticks=2)
json.dump(S,open('og_specs1.json','w'),indent=0)
print(len(S))
